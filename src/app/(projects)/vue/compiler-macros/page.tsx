import { notFound } from "next/navigation";
import PageShell from "@/components/ui/page-shell";
import SummaryArticles, {
    Mono,
    type SummaryArticle,
} from "@/components/ui/summary-articles";
import {
    CompilerMacrosDocs,
    SECTION_SEVERITIES,
} from "@/projects/vue/content/compiler-macros";
import { topicBySlug } from "@/projects/vue/vue";

// Glanceable chapter takeaways — reading only these gives the whole page.
// Each href targets a DocSection id (slugged from its title in the content file).
// AUDIT RULE: every DocSection on this page must have exactly one article here,
// and every article must point at a real section id. No pinned footer sections,
// so the rule holds for all seven without exception: 7 sections, 7 cards.
const PROPS_TEXT = [
    {
        title: "Typed props",
        href: "#typed-props",
        text: <>Props as a TypeScript type; runtime options generated by the compiler.</>,
    },
    {
        title: "Defaults and destructuring",
        href: "#defaults-and-destructuring",
        text: (
            <>
                Destructure with defaults (3.5+), stays reactive; <Mono>watch</Mono>{" "}
                via a getter.
            </>
        ),
    },
];

const EMITS_TEXT = [
    {
        title: "Typed events",
        href: "#typed-events",
        text: (
            <>
                Named tuples type each event; returns the typed <Mono>emit</Mono>{" "}
                function.
            </>
        ),
    },
];

const MODEL_TEXT = [
    {
        title: "v-model in one line",
        href: "#v-model-in-one-line",
        text: (
            <>
                Prop + event + writable ref; named models for{" "}
                <Mono>v-model:name</Mono>.
            </>
        ),
    },
];

const EXPOSE_OPTIONS_TEXT = [
    {
        title: "defineExpose",
        href: "#defineexpose",
        text: <>Opens chosen members to parent refs; expose actions, not data.</>,
    },
    {
        title: "defineOptions",
        href: "#defineoptions",
        text: (
            <>
                <Mono>name</Mono> and <Mono>inheritAttrs</Mono> without a second script
                block.
            </>
        ),
    },
];

const SLOTS_TEXT = [
    {
        title: "Typed slots",
        href: "#typed-slots",
        text: <>Slots as functions of their props; parent slot props are typed.</>,
    },
];

// Severities are DERIVED from SECTION_SEVERITIES by href — never hand-set here,
// so every card matches the section it links to by construction.
const withSeverities = (item: {
    title: string;
    href: string;
    text: React.ReactNode;
}): SummaryArticle => ({
    ...item,
    severities: SECTION_SEVERITIES[item.href.replace("#", "")],
});

const PROPS: SummaryArticle[] = PROPS_TEXT.map(withSeverities);
const EMITS: SummaryArticle[] = EMITS_TEXT.map(withSeverities);
const MODEL: SummaryArticle[] = MODEL_TEXT.map(withSeverities);
const EXPOSE_OPTIONS: SummaryArticle[] = EXPOSE_OPTIONS_TEXT.map(withSeverities);
const SLOTS: SummaryArticle[] = SLOTS_TEXT.map(withSeverities);

export default function Page() {
    const topic = topicBySlug("compiler-macros");
    if (!topic) notFound();

    return (
        <PageShell
            alerts={
                <SummaryArticles
                    groups={[
                        { label: "defineProps", items: PROPS },
                        { label: "defineEmits", items: EMITS },
                        { label: "defineModel", items: MODEL },
                        {
                            label: "defineExpose and defineOptions",
                            items: EXPOSE_OPTIONS,
                        },
                        { label: "defineSlots", items: SLOTS },
                    ]}
                />
            }
        >
            {/* Same arrangement as the app-instance page: no DemoFrame and no
                "use client", header inlined, heading and summary from the
                registry so the page, its sidebar row and its landing card can
                never drift. */}
            <article className="w-full">
                <header className="mb-6">
                    <p className="font-mono text-xs tracking-widest text-[var(--muted)]">
                        Vue · Script Setup
                    </p>
                    <h1 className="mt-1 text-3xl font-semibold text-[var(--text)]">
                        {topic.name}
                    </h1>
                    <div className="mt-3 text-[var(--muted)] leading-relaxed">
                        {topic.summary}
                    </div>
                </header>

                <CompilerMacrosDocs />
            </article>
        </PageShell>
    );
}
